const MAP_SIZE: usize = 0x100000;

#[derive(Debug, Clone)]
struct HarnessTarget {
    name: String,
    port: u16,
    cpus: [u32; 2],
}

#[derive(Debug, Parser)]
#[command(
    name = "check_corpus",
    about = "Replay cases generated by my_h3_fuzzer"
)]
struct Opt {
    #[arg(
        help = "first harness name",
        name = "first_name",
        default_value = "h2o"
    )]
    first_name: String,

    #[arg(
        help = "second harness name",
        name = "second_name",
        default_value = "nginx"
    )]
    second_name: String,

    #[arg(
        help = "case file(s) or directories to replay; defaults to ./crashes when omitted",
        name = "inputs"
    )]
    inputs: Vec<PathBuf>,
}

fn parse_line(line: &str) -> Option<HarnessTarget> {
    let parts: Vec<&str> = line.split_whitespace().collect();
    if parts.len() != 3 {
        return None;
    }

    let cpus: Vec<u32> = parts[2]
        .split(',')
        .map(|s| s.parse::<u32>())
        .collect::<Result<Vec<_>, _>>()
        .ok()?;

    if cpus.len() != 2 {
        return None;
    }

    Some(HarnessTarget {
        name: parts[0].trim_end_matches(':').to_string(),
        port: parts[1].parse().ok()?,
        cpus: [cpus[0], cpus[1]],
    })
}

fn configure_h3_runtime_defaults() {
    let defaults = [
        ("MERCURIUZZ_H3_MAX_STREAM_WRITE_SLICE", "4096"),
        ("MERCURIUZZ_H3_MAX_IMMEDIATE_ACTIONS", "1024"),
        ("MERCURIUZZ_H3_ACTION_BUDGET_MS", "15"),
        ("MERCURIUZZ_H3_BATCH_DRAIN_MS", "80"),
        ("MERCURIUZZ_H3_MAX_TESTCASE_BYTES", "4194304"),
        ("MERCURIUZZ_H3_MAX_GENERATED_ACTIONS", "8192"),
    ];

    for (key, value) in defaults {
        if env::var_os(key).is_none() {
            env::set_var(key, value);
        }
    }
}

fn init_runtime_env() -> Result<(), Box<dyn std::error::Error>> {
    env::set_current_dir(env!("CARGO_MANIFEST_DIR"))?;
    env::set_var("START_DIR", "start");
    env::set_var("JUDGE_DIR", "judge");
    env::set_var("PCAPS_DIR", "pcaps");
    configure_h3_runtime_defaults();
    if env::var_os("SSLKEYLOGFILE").is_none() {
        env::set_var("SSLKEYLOGFILE", "/media/john/Data/key.log");
    }
    let _ = env_logger::Builder::from_env(env_logger::Env::default().default_filter_or("info"))
        .try_init();
    Ok(())
}

fn load_targets(
    first_name: &str,
    second_name: &str,
) -> Result<(HarnessTarget, HarnessTarget), Box<dyn std::error::Error>> {
    let file = File::open("start/ports")?;
    let reader = BufReader::new(file);
    let mut targets = Vec::new();

    for line in reader.lines() {
        let line = line?;
        if let Some(target) = parse_line(&line) {
            if target.name == first_name || target.name == second_name {
                targets.push(target);
            }
        }
    }

    if targets.len() != 2 {
        return Err(io::Error::new(
            io::ErrorKind::NotFound,
            format!("failed to find both harnesses in start/ports: {first_name}, {second_name}"),
        )
        .into());
    }

    if targets[0].name == second_name {
        targets.reverse();
    }

    Ok((targets[0].clone(), targets[1].clone()))
}

fn collect_case_paths(inputs: &[PathBuf]) -> Result<Vec<PathBuf>, Box<dyn std::error::Error>> {
    let mut case_paths = Vec::new();

    for input in inputs {
        if input.is_file() {
            case_paths.push(input.clone());
            continue;
        }

        if input.is_dir() {
            let mut entries = fs::read_dir(input)?
                .filter_map(Result::ok)
                .map(|entry| entry.path())
                .filter(|path| path.is_file())
                .collect::<Vec<_>>();
            entries.sort();
            case_paths.extend(entries);
            continue;
        }

        return Err(io::Error::new(
            io::ErrorKind::NotFound,
            format!("input path does not exist: {}", input.display()),
        )
        .into());
    }

    case_paths.sort();
    case_paths.dedup();

    if case_paths.is_empty() {
        return Err(io::Error::new(io::ErrorKind::NotFound, "no replay cases found").into());
    }

    Ok(case_paths)
}

fn parse_seed(path: &Path) -> Option<u32> {
    path.file_name()?
        .to_str()?
        .strip_prefix("seed_")?
        .parse::<u32>()
        .ok()
}

fn wait_for_enter(
    case_path: &Path,
    current: usize,
    total: usize,
) -> Result<(), Box<dyn std::error::Error>> {
    if current < total {
        print!(
            "[{current}/{total}] finished {}. Press Enter to continue...",
            case_path.display()
        );
    } else {
        print!(
            "[{current}/{total}] finished {}. Press Enter to exit...",
            case_path.display()
        );
    }
    io::stdout().flush()?;

    let mut line = String::new();
    let bytes = io::stdin().read_line(&mut line)?;
    println!();
    if bytes == 0 {
        return Err(io::Error::new(
            io::ErrorKind::UnexpectedEof,
            "stdin closed while waiting for Enter",
        )
        .into());
    }
    Ok(())
}

fn run() -> Result<(), Box<dyn std::error::Error>> {
    init_runtime_env()?;
    let opt = Opt::parse();
    let requested_inputs = if opt.inputs.is_empty() {
        vec![PathBuf::from("crashes")]
    } else {
        opt.inputs.clone()
    };
    let case_paths = collect_case_paths(&requested_inputs)?;

    let (first_target, second_target) = load_targets(&opt.first_name, &opt.second_name)?;
    info!(
        "First project: {}, port: {}, cpus: {}, {}",
        first_target.name, first_target.port, first_target.cpus[0], first_target.cpus[1]
    );
    info!(
        "Second project: {}, port: {}, cpus: {}, {}",
        second_target.name, second_target.port, second_target.cpus[0], second_target.cpus[1]
    );
    info!("Replaying {} case(s)", case_paths.len());

    let mut shmem_provider = StdShMemProvider::new()?;
    let mut first_edge_map = shmem_provider.new_shmem(MAP_SIZE)?;
    let mut second_edge_map = shmem_provider.new_shmem(MAP_SIZE)?;
    let first_edge_map_id = first_edge_map.id().to_string();
    let second_edge_map_id = second_edge_map.id().to_string();

    let mut diff_map_observer = HitcountsIterableMapObserver::new(MultiMapObserver::new(
        "combined-edges",
        vec![
            unsafe {
                OwnedMutSlice::from_raw_parts_mut(
                    first_edge_map.as_slice_mut().as_mut_ptr(),
                    MAP_SIZE,
                )
            },
            unsafe {
                OwnedMutSlice::from_raw_parts_mut(
                    second_edge_map.as_slice_mut().as_mut_ptr(),
                    MAP_SIZE,
                )
            },
        ],
    ));
    let _ = diff_map_observer.base.reset_map();

    let first_time_observer = TimeObserver::new("time");
    let first_recv_pkt_num_observer = RecvPktNumObserver::new("recv_pkt_num");
    let first_conn_observer = NormalConnObserver::new(
        "conn1",
        "127.0.0.1".to_owned(),
        first_target.port,
        "k4ra5u.xx".to_owned(),
    );
    let mut first_cc_time_observer = CCTimesObserver::new("cc_time");
    let mut first_cpu_usage_observer = CPUUsageObserver::new("first_cpu_usage");
    let mut first_mem_observer = MemObserver::new("mem");
    let first_ucb_observer = UCBObserver::new("ucb1");
    let mut first_misc_observer = MiscObserver::new("misc");
    let mut first_pcap_observer = PcapObserver::new("pcap");
    first_cpu_usage_observer.add_cpu_id(first_target.cpus[0]);
    first_cpu_usage_observer.add_cpu_id(first_target.cpus[1]);

    let second_time_observer = TimeObserver::new("time");
    let second_recv_pkt_num_observer = RecvPktNumObserver::new("recv_pkt_num");
    let second_conn_observer = NormalConnObserver::new(
        "conn2",
        "127.0.0.1".to_owned(),
        second_target.port,
        "k4ra5u.xx".to_owned(),
    );
    let mut second_cc_time_observer = CCTimesObserver::new("cc_time");
    let mut second_cpu_usage_observer = CPUUsageObserver::new("second_cpu_usage");
    let mut second_mem_observer = MemObserver::new("mem");
    let second_ucb_observer = UCBObserver::new("ucb2");
    let mut second_misc_observer = MiscObserver::new("misc");
    let mut second_pcap_observer = PcapObserver::new("pcap");
    second_cpu_usage_observer.add_cpu_id(second_target.cpus[0]);
    second_cpu_usage_observer.add_cpu_id(second_target.cpus[1]);

    let diff_cc_observer =
        DifferentialCCTimesObserver::new(&mut first_cc_time_observer, &mut second_cc_time_observer);
    let diff_cpu_observer = DifferentialCPUUsageObserver::new(
        &mut first_cpu_usage_observer,
        &mut second_cpu_usage_observer,
    );
    let diff_mem_observer =
        DifferentialMemObserver::new(&mut first_mem_observer, &mut second_mem_observer);
    let diff_pcap_observer =
        DifferentialPcapObserver::new(&mut first_pcap_observer, &mut second_pcap_observer);
    let diff_misc_observer =
        DifferentialMiscObserver::new(&mut first_misc_observer, &mut second_misc_observer);

    let scheduler = MCTSScheduler::new(&first_ucb_observer);
    let first_normal_conn_feedback = NormalConnFeedback::new(&first_conn_observer);
    let second_normal_conn_feedback = NormalConnFeedback::new(&second_conn_observer);

    let mut feedback = feedback_or!(
        UCBFeedback::new(
            &first_ucb_observer,
            &first_cpu_usage_observer,
            &first_mem_observer,
            &first_cc_time_observer,
            &first_recv_pkt_num_observer
        ),
        UCBFeedback::new(
            &second_ucb_observer,
            &second_cpu_usage_observer,
            &second_mem_observer,
            &second_cc_time_observer,
            &second_recv_pkt_num_observer
        ),
    );
    let mut objective = feedback_or!(
        CrashFeedback::new(),
        NormalDifferFeedback::new(
            &diff_cpu_observer,
            &diff_mem_observer,
            &diff_pcap_observer,
            &diff_misc_observer
        ),
        H3DifferFeedback::new(&diff_cc_observer),
        first_normal_conn_feedback,
        second_normal_conn_feedback,
    );

    let mut state = StdState::new(
        StdRand::with_seed(0),
        InMemoryCorpus::<BytesInput>::new(),
        OnDiskCorpus::new(PathBuf::from("./crashes-validation"))?,
        &mut feedback,
        &mut objective,
    )?;

    let monitor = SimpleMonitor::with_user_monitor(|line| {
        println!("{line}\n");
    });
    let mut mgr = SimpleEventManager::new(monitor);
    let mut fuzzer = StdFuzzer::new(scheduler, feedback, objective);

    let first_observers = tuple_list!(
        first_time_observer,
        first_recv_pkt_num_observer,
        first_ucb_observer,
        first_conn_observer,
        first_cc_time_observer,
        first_cpu_usage_observer,
        first_mem_observer,
        first_misc_observer,
        first_pcap_observer,
        diff_map_observer
    );
    let second_observers = tuple_list!(
        second_time_observer,
        second_recv_pkt_num_observer,
        second_ucb_observer,
        second_conn_observer,
        second_cc_time_observer,
        second_cpu_usage_observer,
        second_mem_observer,
        second_misc_observer,
        second_pcap_observer,
    );
    let diff_observers = tuple_list!(
        diff_cc_observer,
        diff_cpu_observer,
        diff_mem_observer,
        diff_pcap_observer,
        diff_misc_observer,
    );

    let mut rng = rand::rng();
    let frame_rand_seed = rng.random();
    unsafe {
        srand(frame_rand_seed);
    }

    let first_executor = H3Executor::new(first_observers, shmem_provider.clone())
        .start_command(first_target.name.clone())
        .judge_command(first_target.name.clone())
        .is_first()
        .port(first_target.port)
        .timeout(Duration::from_millis(1000))
        .coverage_map_size(MAP_SIZE)
        .envs(vec![
            ("__AFL_SHM_ID".to_string(), first_edge_map_id),
            ("__AFL_SHM_ID_SIZE".to_string(), MAP_SIZE.to_string()),
        ])
        .set_frame_seed(frame_rand_seed)
        .build_h3_conn_struct(
            "k4ra5u.xx".to_owned(),
            first_target.port,
            "127.0.0.1".to_owned(),
        )
        .build();

    let second_executor = H3Executor::new(second_observers, shmem_provider.clone())
        .start_command(second_target.name.clone())
        .judge_command(second_target.name.clone())
        .port(second_target.port)
        .timeout(Duration::from_millis(1000))
        .coverage_map_size(MAP_SIZE)
        .envs(vec![
            ("__AFL_SHM_ID".to_string(), second_edge_map_id),
            ("__AFL_SHM_ID_SIZE".to_string(), MAP_SIZE.to_string()),
        ])
        .set_frame_seed(frame_rand_seed)
        .build_h3_conn_struct(
            "k4ra5u.xx".to_owned(),
            second_target.port,
            "127.0.0.1".to_owned(),
        )
        .build();

    let mut differential_executor =
        DiffExecutor::new(first_executor, second_executor, diff_observers);

    for (idx, case_path) in case_paths.iter().enumerate() {
        let seed = parse_seed(case_path).unwrap_or(0);
        if seed == 0 {
            warn!(
                "case {} does not match seed_<u32>; replaying with rand_seed=0",
                case_path.display()
            );
        } else {
            info!("replaying {} with rand_seed={seed}", case_path.display());
        }

        state.set_rand_seed(seed);
        let before_corpus = state.corpus().count();
        let before_solutions = state.solutions().count();
        let input = BytesInput::from_file(case_path)?;
        let (result, _) =
            fuzzer.evaluate_input(&mut state, &mut differential_executor, &mut mgr, input)?;

        info!(
            "finished {}: result={result:?}, new_corpus={}, new_solution={}",
            case_path.display(),
            state.corpus().count() > before_corpus,
            state.solutions().count() > before_solutions,
        );
        wait_for_enter(case_path, idx + 1, case_paths.len())?;
    }

    info!(
        "Replay finished: total_cases={}, corpus_entries={}, solution_entries={}",
        case_paths.len(),
        state.corpus().count(),
        state.solutions().count(),
    );
    Ok(())
}

fn main() {
    if let Err(err) = run() {
        eprintln!("check_corpus failed: {err}");
        process::exit(1);
    }
}
